import { readFileSync } from "node:fs";
import vm from "node:vm";
let bad = 0;
const ok = (c, m) => { console.log((c ? "PASS  " : "FAIL  ") + m); if (!c) { bad++; } };
const src = readFileSync(new URL("../worker/index.js", import.meta.url), "utf8");
const i = src.indexOf("function clientTermsFromHistory(");
const j = src.indexOf("\n}\n", i) + 3;
const ctx = vm.createContext({});
vm.runInContext(src.slice(i, j), ctx);
const f = ctx.clientTermsFromHistory;
const gator = [{ date: "2026-08-03", amount_cents: 150000 }, { date: "2026-09-01", amount_cents: 150000 }, { date: "2026-10-01", amount_cents: 150000 }];
let r = f(gator);
ok(r.frequency && r.frequency.frequency === "monthly", "three monthly payments: frequency is monthly");
ok(r.amount && r.amount.amount_cents === 150000, "same amount every time: amount is known");
r = f(gator.slice(0, 2));
ok(!r.frequency && !r.amount, "two payments is not enough to claim anything");
r = f([{ date: "2026-08-03", amount_cents: 150000 }, { date: "2026-09-01", amount_cents: 120000 }, { date: "2026-10-01", amount_cents: 150000 }]);
ok(r.frequency && !r.amount, "varying amounts: monthly yes, amount not guessed");
r = f([{ date: "2026-08-03", amount_cents: 100 }, { date: "2026-08-10", amount_cents: 100 }, { date: "2026-08-17", amount_cents: 100 }]);
ok(!r.frequency, "weekly gaps are not called monthly");
r = f([{ date: "2026-06-03", amount_cents: 100 }, { date: "2026-09-01", amount_cents: 100 }, { date: "2026-10-01", amount_cents: 100 }]);
ok(!r.frequency, "a three-month gap breaks the monthly pattern");
console.log(bad ? bad + " FAILED" : "ALL PASSED"); process.exit(bad ? 1 : 0);
